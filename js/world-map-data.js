/* 弧线路径计算：bend "up" 向上拱起（默认），"right" 向右弯（南向航线） */
function routePath(a, b, lift, bend) {
  var mx = (a.x + b.x) / 2;
  var my = (a.y + b.y) / 2;
  if (bend === "right") {
    return "M " + a.x + " " + a.y + " Q " + (mx + lift) + " " + my + " " + b.x + " " + b.y;
  }
  return "M " + a.x + " " + a.y + " Q " + mx + " " + (Math.min(a.y, b.y) - lift) + " " + b.x + " " + b.y;
}
